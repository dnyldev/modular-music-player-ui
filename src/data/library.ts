const AUDIO_EXT = /\.(mp3|wav|flac|aac|m4a|ogg|aiff|aif)$/i;
const MAX_BYTES = 50 * 1024 * 1024;

export function isAudioFile(file: File) {
  if (file.type.startsWith("audio/")) return true;
  return AUDIO_EXT.test(file.name);
}

export function validateUpload(file: File, existing: Track[]) {
  if (!file || file.size === 0) return { ok: false as const, reason: "empty" as const };
  if (!isAudioFile(file)) return { ok: false as const, reason: "format" as const };
  if (file.size > MAX_BYTES) return { ok: false as const, reason: "size" as const };
  const stem = file.name.replace(/\.[^.]+$/, "").toLowerCase();
  const dup = existing.some((t) => t.title.toLowerCase() === stem);
  if (dup) return { ok: false as const, reason: "duplicate" as const };
  return { ok: true as const };
}

